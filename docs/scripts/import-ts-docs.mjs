#!/usr/bin/env node
// Imports ts/docs/v1.9.0/* (the hand-written markdown that has always lived
// next to the TS source) into this Docusaurus site's "ts" docs-plugin instance
// as the v1.9.0 versioned snapshot (ts_versioned_docs/version-1.9.0/).
//
// Scope decision: the docs site only documents the latest released TS version
// (v1.9.0) plus v2.0.0 (the in-progress builder-pattern API, authored directly
// into docs-ts/ - see Phase 6 of TODO.md). Versions v0.0.1-v1.8.0 are not
// imported; ts/docs/ remains the historical record for those.
//
// Re-run safe: wipes and rebuilds ts_versioned_docs/, ts_versioned_sidebars/ and
// ts_versions.json from scratch every time.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DOCS_ROOT = path.resolve(__dirname, '..');
const SOURCE_DIR = path.resolve(DOCS_ROOT, '../ts/docs/v1.9.0');
const VERSION_LABEL = '1.9.0';
const DEST_DIR = path.join(DOCS_ROOT, 'ts_versioned_docs', `version-${VERSION_LABEL}`);
const DEST_SIDEBARS_ROOT = path.join(DOCS_ROOT, 'ts_versioned_sidebars');
const VERSIONS_JSON_PATH = path.join(DOCS_ROOT, 'ts_versions.json');

function copyRecursive(srcDir, destDir) {
  fs.mkdirSync(destDir, { recursive: true });
  for (const entry of fs.readdirSync(srcDir, { withFileTypes: true })) {
    const srcPath = path.join(srcDir, entry.name);
    const destPath = path.join(destDir, entry.name);
    if (entry.isDirectory()) {
      copyRecursive(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

// Docusaurus needs a resolvable title per doc. These source files use plain
// markdown headings (sometimes h1, sometimes h2) with no frontmatter, so inject
// a `title` derived from the first heading line whenever frontmatter is absent.
function ensureFrontmatter(filePath) {
  const original = fs.readFileSync(filePath, 'utf8');
  if (original.startsWith('---\n')) return; // already has frontmatter

  const headingMatch = /^#{1,6}\s+(.+)$/m.exec(original);
  if (!headingMatch) return;

  const title = headingMatch[1].trim().replace(/"/g, '\\"');
  const frontmatter = `---\ntitle: "${title}"\n---\n\n`;
  fs.writeFileSync(filePath, frontmatter + original);
}

// The playground embed is JSX (<TsPlayground .../>), which would render oddly
// on GitHub where ts/docs/v1.9.0/index.md is also viewed as plain markdown - so
// it's appended here to the *imported copy* only, not written into the source
// file. Keep this in sync with src/components/TsPlayground/.
const PLAYGROUND_SNIPPET = `
## Try it in the browser

<TsPlayground
  ivoVersion="${VERSION_LABEL}"
  code={\`
import { Schema, type IvoSummary } from 'ivo';

type UserInput = {
  email: string | null;
  username: string;
};

type User = {
  id: string;
  createdAt: Date;
  email: string | null;
  username: string;
};

const userSchema = new Schema<UserInput, User>(
  {
    id: { constant: true, value: () => Math.random().toString(36).slice(2) },
    email: {
      default: null,
      validator: (value: string) =>
        typeof value === 'string' && value.includes('@')
          ? true
          : { valid: false, reason: 'Invalid email' },
    },
    username: {
      required: true,
      validator: (value: string) =>
        value.length >= 3
          ? true
          : { valid: false, reason: 'Username too short' },
    },
  },
  { timestamps: true },
);

const UserModel = userSchema.getModel();

async function main() {
  const { data, error } = await UserModel.create({
    email: 'john.doe@mail.com',
    username: 'john_doe',
  });

  console.log('data:', data);
  console.log('error:', error);
}

main();
\`}
/>
`;

function appendPlayground(indexMdPath) {
  fs.appendFileSync(indexMdPath, PLAYGROUND_SNIPPET);
}

function forEachMarkdownFile(dir, fn) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const entryPath = path.join(dir, entry.name);
    if (entry.isDirectory()) forEachMarkdownFile(entryPath, fn);
    else if (entry.name.endsWith('.md') || entry.name.endsWith('.mdx')) fn(entryPath);
  }
}

function main() {
  if (!fs.existsSync(SOURCE_DIR)) {
    console.error(`Source docs not found at ${SOURCE_DIR}`);
    process.exit(1);
  }

  fs.rmSync(path.join(DOCS_ROOT, 'ts_versioned_docs'), { recursive: true, force: true });
  fs.rmSync(DEST_SIDEBARS_ROOT, { recursive: true, force: true });
  fs.mkdirSync(DEST_SIDEBARS_ROOT, { recursive: true });

  copyRecursive(SOURCE_DIR, DEST_DIR);
  forEachMarkdownFile(DEST_DIR, ensureFrontmatter);
  appendPlayground(path.join(DEST_DIR, 'index.md'));

  fs.writeFileSync(
    path.join(DEST_SIDEBARS_ROOT, `version-${VERSION_LABEL}-sidebars.json`),
    `${JSON.stringify({ tsSidebar: [{ type: 'autogenerated', dirName: '.' }] }, null, 2)}\n`,
  );

  fs.writeFileSync(VERSIONS_JSON_PATH, `${JSON.stringify([VERSION_LABEL], null, 2)}\n`);

  console.log(`imported v1.9.0 -> ts_versioned_docs/version-${VERSION_LABEL}/`);
  console.log(`Wrote ${VERSIONS_JSON_PATH}`);
}

main();
